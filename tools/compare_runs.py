"""Compare two extraction runs of one handbook and topic, statement by statement, in the database.

Two statements are candidates when they cite the same handbook text: a sentence in common (or a
figure), whatever passages each run cut. Pairs are taken greedily, best first: by overlap of the
sentences cited (Jaccard), then same type, then word overlap of the text. Every number is agreement
with the other run, not correctness.

    python3 tools/compare_runs.py on-passing-1 on-passing-ref [--report runs/on-passing-1/compare.md]
"""
import argparse
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import db as dbtool  # noqa: E402

MODAL = re.compile(r'\b(MUST NOT|MUST|MAY|SHOULD NOT|SHOULD)\b')
CLAUSES = ['ONLY IF', 'IF VIOLATED', 'WHEN', 'WHILE', 'UNLESS', 'UNTIL', 'BECAUSE']
INLINE = set('JSRG')


def words(t):
    return set(re.findall(r'[a-z0-9]+', re.sub(r'\b[A-Z]{2,}\b', ' ', t).lower()))


def body(t):
    return t.split(':', 1)[1] if t.startswith('EXCEPTION TO') and ':' in t else t


def modals(row):
    # as in provenance/scripts/score_extraction.py: the set of modals, and only for rules
    return sorted(set(MODAL.findall(body(row['text'])))) if row['type'] == 'RULE' else []


def clauses(t):
    t = re.sub(r'\[\?[^\]]*\]', ' ', body(t))
    found = []
    for c in CLAUSES:
        if re.search(r'\b' + c + r'\b', t):
            found.append(c)
            t = re.sub(r'\b' + c + r'\b', ' ', t)
    return sorted(found)


def statements(db, run):
    q = lambda sql, *x: db.execute(sql, x).fetchall()  # noqa: E731
    out = {}
    for s in q('SELECT * FROM statement WHERE run_id = ? ORDER BY position', run):
        cited = {r[0] for r in q("SELECT x.unit_id FROM unit_use x JOIN unit u ON u.id = x.unit_id "
                                 "WHERE x.statement_id = ? AND (u.kind = 'sentence' OR u.image IS NOT NULL)", s['id'])}
        steps = ' '.join(r[0] for r in q('SELECT text FROM statement_step WHERE statement_id = ?', s['id']))
        flags = {(o['code'], dbtool.norm(o['span'])) for o in q('SELECT * FROM occurrence WHERE statement_id = ?', s['id'])}
        out[s['id']] = dict(row=dict(s), cited=cited, all=s['text'] + ' ' + steps, flags=flags)
    return out


def pair(a, b):
    cands = []
    for i, x in a.items():
        for j, y in b.items():
            common = x['cited'] & y['cited']
            if common:
                jac = len(common) / len(x['cited'] | y['cited'])
                same = x['row']['type'] == y['row']['type']
                wa, wb = words(x['all']), words(y['all'])
                cands.append((-jac, -same, -len(wa & wb) / max(1, len(wa | wb)), i, j))
    used_a, used_b, pairs = set(), set(), []
    for *_, i, j in sorted(cands):
        if i not in used_a and j not in used_b:
            pairs.append((i, j))
            used_a.add(i)
            used_b.add(j)
    return pairs


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('run')
    ap.add_argument('other')
    ap.add_argument('--report')
    a = ap.parse_args()
    db = dbtool.connect()
    A, B = statements(db, a.run), statements(db, a.other)
    pairs = pair(A, B)
    agree = collections.Counter()
    differ = []
    for i, j in pairs:
        x, y = A[i]['row'], B[j]['row']
        what = []
        for key, same in (('type', x['type'] == y['type']), ('strength', x['strength'] == y['strength']),
                          ('modal', modals(x) == modals(y)),
                          ('clauses', clauses(x['text']) == clauses(y['text']))):
            agree[key] += same
            if not same:
                what.append(key)
        if what:
            differ.append((i, j, what))
    fa = {(i, f) for i, s in A.items() for f in s['flags'] if f[0] in INLINE}
    fb = {(j, f) for j, s in B.items() for f in s['flags'] if f[0] in INLINE}
    match = {j: i for i, j in pairs}
    hit = sum(1 for j, f in fb if j in match and (match[j], f) in fa)
    n = len(pairs)
    pct = lambda k, d: f'{k}/{d} ({round(100 * k / d) if d else 0}%)'  # noqa: E731
    bytype = lambda S: ', '.join(f'{t} {c}' for t, c in sorted(collections.Counter(s['row']['type'] for s in S.values()).items()))  # noqa: E731
    out = [f'# {a.run} compared with {a.other}', '',
           f'Generated by `tools/compare_runs.py {a.run} {a.other}` from the database. Pairs share handbook text; '
           'every number is agreement, not correctness.', '',
           '## Summary', '',
           f'- Statements: {a.run} {len(A)} ({bytype(A)}); {a.other} {len(B)} ({bytype(B)}).',
           f'- Paired: {n}. {a.other} found again: {pct(n, len(B))}; {a.run} paired: {pct(n, len(A))}.',
           f'- On paired statements: type {pct(agree["type"], n)}, strength {pct(agree["strength"], n)}, '
           f'modals {pct(agree["modal"], n)}, clause keywords {pct(agree["clauses"], n)}.',
           f'- Inline flags (J, S, R, G) of {a.other} found on the paired statement: {pct(hit, len(fb))}; '
           f'{a.run} has {len(fa)} inline flags.', '']
    if differ:
        out += ['## Paired statements that differ', '', f'| {a.other} | {a.run} | Differs in | {a.other} text | {a.run} text |',
                '|---|---|---|---|---|']
        out += [f'| {B[j]["row"]["local_id"]} | {A[i]["row"]["local_id"]} | {", ".join(w)} | '
                f'{B[j]["row"]["text"].replace("|", "/")} | {A[i]["row"]["text"].replace("|", "/")} |' for i, j, w in differ]
        out.append('')
    for name, S, used in ((a.other, B, {j for _, j in pairs}), (a.run, A, {i for i, _ in pairs})):
        left = [s for k, s in S.items() if k not in used]
        out += [f'## {name}: not paired ({len(left)})', '']
        out += [f'- {s["row"]["local_id"]} ({s["row"]["type"]}): {s["row"]["text"]}' for s in left] or ['- none']
        out.append('')
    text = '\n'.join(out)
    if a.report:
        open(os.path.join(dbtool.ROOT, a.report), 'w', encoding='utf-8').write(text)
    print('\n'.join(out[6:10]))


if __name__ == '__main__':
    main()
